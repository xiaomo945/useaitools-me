let maxId = tools.reduce((max, t) => Math.max(max, t.id), 0);
const added = [];

for (const candidate of candidates) {
  if (existingNames.has(candidate.name.toLowerCase()) || existingUrls.has(candidate.url)) {
    console.log(`Skipping existing tool: ${candidate.name}`);
    continue;
  }

  const id = ++maxId;
  const slug = generateSlug(candidate.name);
  const tool = {
    id,
    name: candidate.name,
    description: candidate.description,
    description_en: candidate.description_en,
    category: candidate.category,
    pricing: candidate.pricing,
    url: candidate.url,
    affiliate_link: '',
    icon_url: '',
    examples: [
      {
        prompt: `Example use case for ${candidate.name}`,
        image_url: 'https://placehold.co/600x400/1a1a2e/eee?text=AI+Tool',
      },
    ],
    needs_vpn: candidate.needs_vpn,
    languages: candidate.languages,
    rating: 4.3,
    rating_count: 150,
    rating_breakdown: makeRatings(),
    last_updated: new Date().toISOString().split('T')[0],
    skill_level: candidate.skill_level,
    best_for: candidate.best_for,
  };

  tools.push(tool);
  added.push(candidate.name);
}

